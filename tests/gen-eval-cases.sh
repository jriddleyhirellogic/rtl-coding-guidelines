#!/usr/bin/env bash
# Generate one `claude plugin eval` case per golden fixture.
#
# The fixtures are the source of truth; these case.yaml files are build output,
# the same relationship NTL_*.html has to rule-index.md. Inlining the RTL into
# the prompt (rather than pointing at a path) keeps each case independent of
# wherever the eval runner sets its working directory.
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$script_dir/.." && pwd)"
. "$script_dir/lib.sh"

EVALS_DIR="$SKILL_DIR/evals"

# Lines beginning with //! are fixture annotations that name the planted
# defect. They have to go, or the prompt hands the model the answer it is
# supposed to find. Also drop the blank lines they leave at the top.
strip_annotations() {
  sed '/^[[:space:]]*\/\/!/d' "$1" | sed '/./,$!d' | sed 's/[[:space:]]*$//'
}

# Remove previously generated cases, so deleting a fixture does not leave a
# stale case behind to fail forever. Match on the GENERATED marker rather than
# the review-* name: hand-written cases share that prefix, and a name-based
# sweep would silently eat them.
while IFS= read -r c; do
  [ -f "$c" ] || continue
  head -1 "$c" | grep -q '^# GENERATED by tests/gen-eval-cases.sh' && rm -rf "$(dirname "$c")"
done < <(find "$EVALS_DIR" -mindepth 2 -maxdepth 2 -name case.yaml 2>/dev/null)

count=0
for fx in $(golden_fixtures); do
  rtl="$GOLDEN_DIR/rtl/$fx.v"
  exp="$GOLDEN_DIR/expected/$fx.expect"
  [ -f "$exp" ] || { echo "skipping $fx: no .expect file" >&2; continue; }

  summary=$(expect_field "$exp" summary)
  must=$(expect_field "$exp" must_flag)
  mustnt=$(expect_field "$exp" must_not_flag)

  case_dir="$EVALS_DIR/review-$fx"
  mkdir -p "$case_dir"

  {
    echo "# GENERATED by tests/gen-eval-cases.sh from tests/golden/$fx.*"
    echo "# Edit the fixture or its .expect file and regenerate; do not edit this."
    echo 'schema_version: "1.0"'
    echo "name: review-$fx"
    echo "description: $summary"
    echo "tags: [review, golden]"
    echo "execution:"
    echo "  prompt: |"
    echo "    Review the Verilog module below against our RTL coding guidelines and"
    echo "    report every violation you find. For each one give the rule ID, the"
    echo "    line, what is wrong, and the fix."
    echo ""
    echo "    \`\`\`verilog"
    strip_annotations "$rtl" | sed 's/^./    &/'
    echo "    \`\`\`"
    echo "  max_turns: 25"
    echo "  timeout_seconds: 420"
    echo "  allowed_tools: [Read, Glob, Grep, Skill]"
    echo "runs: 3"
    echo "graders:"

    # Marked with-only: under the default with/without ablation this reports
    # whether the skill fired at all, without inflating the score.
    echo "  - type: tool_used"
    echo "    name: skill-fired"
    echo "    tool: Skill"
    echo "    arm: with-only"

    for id in $must; do
      echo "  - type: regex"
      echo "    name: flags-$id"
      echo "    target: last_message"
      echo "    pattern: \"$id\""
      echo "    match: contains"
      echo "    weight: 2"
    done

    # must_not_flag needs a judge, not a regex. A thorough review names the
    # rules it checked and cleared ("NTL_STR47 - no latch inferred, clean"),
    # so a not_contains match on the bare ID punishes exactly the behaviour we
    # want. The distinction is reported-as-a-violation vs explicitly-cleared,
    # and only a reader can draw it.
    for id in $mustnt; do
      echo "  - type: llm"
      echo "    name: does-not-report-$id"
      echo "    focus: last_message"
      echo "    criteria: |"
      echo "      The response does not report $id as a violation of this module."
      echo "      Listing $id among rules that were checked and found clean, or"
      echo "      saying it does not apply, passes - that is a thorough review, not"
      echo "      a false positive. Only claiming the module actually violates"
      echo "      $id fails."
    done

    echo "  - type: llm"
    echo "    name: findings-are-actionable"
    echo "    focus: last_message"
    if [ -n "$must" ]; then
      echo "    criteria: |"
      echo "      The response reviews the module and reports concrete violations."
      echo "      Each finding names a rule ID, points at a specific line or signal,"
      echo "      explains what is wrong, and proposes a fix that would actually"
      echo "      resolve it. The known defect in this module is: $summary."
      echo "      A response that only summarises the module, or lists rule IDs"
      echo "      without tying them to the code, does not pass."
    else
      echo "    criteria: |"
      echo "      This module is intentionally clean. The response should report no"
      echo "      violations, or only minor stylistic observations that it clearly"
      echo "      marks as non-blocking. Inventing defects that are not present in"
      echo "      the source - a latch, a gated clock, a missing synchronizer - does"
      echo "      not pass."
    fi
  } > "$case_dir/case.yaml"

  count=$((count + 1))
done

echo "Generated $count review case(s) under $EVALS_DIR"
